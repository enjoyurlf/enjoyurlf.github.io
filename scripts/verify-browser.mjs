import { chromium } from '@playwright/test'
import assert from 'node:assert/strict'
import { mkdir, writeFile } from 'node:fs/promises'

const url = 'http://127.0.0.1:5173'
const browser = await chromium.launch({ channel: 'chrome', headless: true })
const errors = []
const checks = []
await mkdir('artifacts', { recursive: true })
try {
  const context = await browser.newContext({ viewport: { width: 1440, height: 1120 }, deviceScaleFactor: 1 })
  const page = await context.newPage()
  page.on('pageerror', error => errors.push(error.message))
  page.on('console', message => { if (message.type() === 'error') errors.push(`${message.text()} (${message.location().url})`) })
  await page.goto(url)
  await page.getByRole('heading', { name: '找到唯一答案' }).waitFor()
  assert.equal(await page.locator('[data-cell]').count(), 49)
  const mines = await page.locator('[data-state="mine"]').evaluateAll(cells => cells.map(c => [Number(c.dataset.row) + 1, Number(c.dataset.col) + 1]))
  assert.deepEqual(mines, [[1,4],[2,7],[3,5],[4,2],[5,6],[6,3],[7,1]])
  await page.screenshot({ path: 'artifacts/desktop.png', fullPage: true })
  checks.push('原图7×7：唯一解和7个坐标正确')

  const colorInput = page.getByLabel('调整青蓝显示颜色', { exact: true })
  await colorInput.evaluate(input => {
    input.value = '#4488aa'
    input.dispatchEvent(new Event('change', { bubbles: true }))
  })
  assert.equal(await page.locator('[data-row="0"][data-col="0"]').evaluate(cell => getComputedStyle(cell).backgroundColor), 'rgb(68, 136, 170)')
  assert.equal(await page.locator('[data-row="0"][data-col="0"]').getAttribute('data-region'), '0')
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await page.getByRole('heading', { name: '找到唯一答案' }).waitFor()
  checks.push('自定义显示颜色即时更新，区域编号不变且可撤销')

  await page.getByRole('switch', { name: '编辑后自动求解', exact: true }).click()
  await page.getByRole('button', { name: '选择浅黄', exact: true }).click()
  await page.locator('[data-row="0"][data-col="0"]').click()
  await page.getByRole('heading', { name: '等待开始求解' }).waitFor()
  await page.getByRole('button', { name: '重新求解', exact: true }).click()
  await page.locator('.solve-summary.waiting').waitFor({ state: 'hidden' })
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await page.getByRole('heading', { name: '等待开始求解' }).waitFor()
  await page.getByRole('switch', { name: '编辑后自动求解', exact: true }).click()
  await page.getByRole('heading', { name: '找到唯一答案' }).waitFor()
  checks.push('关闭自动求解后编辑失效旧答案，手动求解与重新开启正确')

  await page.getByRole('button', { name: '添加', exact: true }).click()
  assert.equal(await page.locator('.swatch-row').count(), 8)
  await page.getByRole('heading', { name: '找到唯一答案' }).waitFor()
  checks.push('添加未用色不影响实际区域和答案')
  await page.getByRole('button', { name: '选择浅黄', exact: true }).click()
  await page.getByRole('button', { name: '删除青蓝', exact: true }).click()
  await page.getByRole('heading', { name: '棋盘约束冲突' }).waitFor()
  assert.equal(await page.locator('[data-region="0"]').count(), 0)
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await page.getByRole('heading', { name: '找到唯一答案' }).waitFor()
  checks.push('删色合并及撤销正确，色数不足明确报错')

  await page.getByRole('button', { name: '选择浅黄', exact: true }).click()
  const start = await page.locator('[data-row="0"][data-col="0"]').boundingBox()
  const end = await page.locator('[data-row="0"][data-col="1"]').boundingBox()
  await page.mouse.move(start.x + start.width / 2, start.y + start.height / 2)
  await page.mouse.down()
  await page.mouse.move(end.x + end.width / 2, end.y + end.height / 2, { steps: 8 })
  await page.mouse.up()
  assert.equal(await page.locator('[data-row="0"][data-col="0"]').getAttribute('data-region'), '1')
  assert.equal(await page.locator('[data-row="0"][data-col="1"]').getAttribute('data-region'), '1')
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  assert.equal(await page.locator('[data-row="0"][data-col="0"]').getAttribute('data-region'), '0')
  assert.equal(await page.locator('[data-row="0"][data-col="1"]').getAttribute('data-region'), '0')
  await page.getByRole('heading', { name: '找到唯一答案' }).waitFor()
  checks.push('鼠标连续涂色和单步撤销正确')

  await page.getByRole('spinbutton', { name: '棋盘边长' }).fill('4')
  await page.getByRole('button', { name: '新建棋盘', exact: true }).click()
  await page.getByRole('heading', { name: '存在 2 个解' }).waitFor()
  assert.equal(await page.locator('[data-cell]').count(), 16)
  assert.equal(await page.locator('[data-state="mine"]').count(), 0)
  assert.equal(await page.locator('[data-state="possible"]').count(), 8)
  await page.getByRole('button', { name: '方案预览', exact: true }).click()
  assert.equal(await page.locator('[data-state="preview"]').count(), 4)
  await page.getByRole('button', { name: '下一方案', exact: true }).click()
  assert.equal(await page.locator('[data-state="preview"]').count(), 4)
  checks.push('自定义4×4、多解推断及方案切换正确')

  await page.getByRole('button', { name: '标雷', exact: true }).click()
  await page.locator('[data-row="0"][data-col="1"]').click()
  await page.getByRole('heading', { name: '找到唯一答案' }).waitFor()
  await page.getByRole('button', { name: '排除', exact: true }).click()
  await page.locator('[data-row="0"][data-col="1"]').click()
  await page.getByRole('heading', { name: '找到唯一答案' }).waitFor()
  await page.getByRole('button', { name: '清除标记', exact: true }).click()
  await page.getByRole('heading', { name: '存在 2 个解' }).waitFor()
  checks.push('手动标雷/安全约束和清除标记正确')

  const downloadPromise = page.waitForEvent('download')
  await page.getByRole('button', { name: '导出棋盘', exact: true }).click()
  const download = await downloadPromise
  await download.saveAs('artifacts/test-puzzle.json')
  await page.getByRole('button', { name: '恢复原图', exact: true }).click()
  await page.getByRole('heading', { name: '找到唯一答案' }).waitFor()
  await page.getByLabel('导入棋盘 JSON', { exact: true }).setInputFiles('artifacts/test-puzzle.json')
  await page.getByRole('heading', { name: '存在 2 个解' }).waitFor()
  await page.reload()
  await page.getByRole('heading', { name: '存在 2 个解' }).waitFor()
  checks.push('JSON导出/导入与刷新后保存正确')

  await page.getByRole('spinbutton', { name: '棋盘边长' }).fill('16')
  await page.getByRole('button', { name: '新建棋盘', exact: true }).click()
  await page.getByRole('heading', { name: '已达到搜索预算' }).waitFor({ timeout: 30_000 })
  assert.equal(await page.locator('[data-cell]').count(), 256)
  assert.equal(await page.locator('[data-state="mine"]').count(), 0)
  checks.push('16×16预算截断，不误标确定雷')

  await page.getByRole('button', { name: '恢复原图', exact: true }).click()
  await page.getByRole('heading', { name: '找到唯一答案' }).waitFor()
  await context.close()

  const mobileContext = await browser.newContext({ viewport: { width: 390, height: 844 }, isMobile: true, hasTouch: true, deviceScaleFactor: 1 })
  const mobile = await mobileContext.newPage()
  mobile.on('pageerror', error => errors.push(error.message))
  await mobile.goto(url)
  await mobile.getByRole('heading', { name: '找到唯一答案' }).waitFor()
  const overflow = await mobile.evaluate(() => document.documentElement.scrollWidth > window.innerWidth)
  assert.equal(overflow, false)
  await mobile.getByRole('button', { name: '选择浅黄', exact: true }).tap()
  await mobile.locator('[data-row="0"][data-col="0"]').tap()
  assert.equal(await mobile.locator('[data-row="0"][data-col="0"]').getAttribute('data-region'), '1')
  await mobile.getByRole('button', { name: '撤销', exact: true }).tap()
  await mobile.getByRole('heading', { name: '找到唯一答案' }).waitFor()
  await mobile.screenshot({ path: 'artifacts/mobile.png', fullPage: true })
  checks.push('390px移动端无横向溢出，触摸涂色与撤销正确')
  await mobileContext.close()
  assert.deepEqual(errors, [])
  const report = { url, checkedAt: new Date().toISOString(), checks, errors }
  await writeFile('artifacts/browser-verification.json', JSON.stringify(report, null, 2))
  console.log(JSON.stringify(report, null, 2))
} finally {
  await browser.close()
}
